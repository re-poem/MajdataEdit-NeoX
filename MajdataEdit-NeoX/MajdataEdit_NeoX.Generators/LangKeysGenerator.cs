using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace MajdataEdit_NeoX.Generators;

/// <summary>
/// 从 Assets/Localizations/en-US.json 提取全部键名,生成
/// MajdataEdit_NeoX.Lang.LangKeys 常量类:
/// <code>
/// public const string Gui_Open = nameof(Gui_Open);
/// </code>
/// 键名即本地化键,运行时经 PropertyGrid 的 LocalizationService 翻译。
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class LangKeysGenerator : IIncrementalGenerator
{
    private static readonly Regex KeyLineRegex = new(
        """^\s*"(?<key>[^"]+?)"\s*:""",
        RegexOptions.Compiled | RegexOptions.Multiline);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var texts = context.AdditionalTextsProvider
            .Where(static f => string.Equals(
                Path.GetFileName(f.Path), "en-US.json", StringComparison.OrdinalIgnoreCase))
            .Select(static (f, ct) => f.GetText(ct)?.ToString() ?? string.Empty)
            .Collect();

        context.RegisterSourceOutput(texts, static (ctx, sources) =>
        {
            var keys = new SortedSet<string>(StringComparer.Ordinal);
            foreach (var text in sources)
            {
                foreach (Match match in KeyLineRegex.Matches(text))
                {
                    var key = match.Groups["key"].Value;
                    if (key.Length > 0 && IsValidIdentifier(key))
                    {
                        keys.Add(key);
                    }
                }
            }

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/> 由 MajdataEdit_NeoX.Generators.LangKeysGenerator 从 en-US.json 生成");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("namespace MajdataEdit_NeoX.Lang;");
            sb.AppendLine();
            sb.AppendLine("/// <summary>本地化键名常量。键名即本地化键,运行时经 LocalizationService 翻译。</summary>");
            sb.AppendLine("public static class LangKeys");
            sb.AppendLine("{");
            foreach (var key in keys)
            {
                sb.Append("    public const string ").Append(key).Append(" = \"").Append(key).AppendLine("\";");
            }
            sb.AppendLine("}");
            ctx.AddSource("LangKeys.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        });
    }

    private static bool IsValidIdentifier(string name)
    {
        if (!char.IsLetter(name[0]) && name[0] != '_') return false;
        for (var i = 1; i < name.Length; i++)
        {
            if (!char.IsLetterOrDigit(name[i]) && name[i] != '_') return false;
        }

        return true;
    }
}
